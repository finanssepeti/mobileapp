export function localeForLang(lang: AppLang): string {
  if (lang === "de") return "de-DE";
  if (lang === "fr") return "fr-FR";
  if (lang === "en") return "en-GB";
  return "tr-TR";
}

export function monthShortLabel(lang: AppLang, month1to12: number): string {
  const k = `month_short_${String(Math.max(1, Math.min(12, month1to12))).padStart(2, "0")}`;
  return t(lang, k);
}

export function t(lang: AppLang, key: string): string {
  const row = I18N[key];
  if (!row) return key;
  const raw = row[lang] ?? row.tr;
  if (key === "cashflow_formula_lines") return raw.replace(/\\n/g, "\n");
  return raw;
}
